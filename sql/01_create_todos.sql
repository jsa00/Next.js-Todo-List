-- 할 일 테이블 (교안 프론트엔드 응용 7장 2강)
-- Supabase 대시보드 > SQL Editor에서 실행

create table if not exists public.todos (
    id bigint generated by default as identity primary key, -- 할 일 고유 번호
    created_at timestamptz not null default now(),          -- 생성 일시
    title text not null,                                    -- 할 일 내용
    is_completed boolean not null default false             -- 완료 여부
);

-- 인증 구현 전이라 RLS를 끄고 CRUD를 확인한다.
-- 다음 단계(7장 3강)에서 user_id 컬럼과 RLS 정책을 추가해 다시 켠다.
alter table public.todos disable row level security;

-- Data API(publishable key)로 접근할 수 있게 권한 부여
grant select, insert, update, delete on public.todos to anon, authenticated;
